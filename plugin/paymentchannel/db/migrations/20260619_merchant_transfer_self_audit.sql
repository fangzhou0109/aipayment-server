-- ----------------------------------------------------------------------
-- 迁移：商户「代付自审」开关（每商户独立配置，平台后台控制）
-- 说明：sa_pay_merchant 增加 transfer_self_audit（0=关闭 / 1=开启）。
--   = 0（默认）：商户的 API 代付「待审核」单仍由平台后台代付订单审核。
--   = 1：商户可在门户「代付订单」页自助「审核下发 / 拒绝」待审核单，
--        通过后后端用平台已授权的代付通道出款；此类单不再进入平台后台审核队列。
-- 仅平台运营在「商户管理」编辑商户时可开关，商户无权自行变更（信任决策）。
-- ----------------------------------------------------------------------
ALTER TABLE `sa_pay_merchant`
  ADD COLUMN `transfer_self_audit` tinyint(1) NOT NULL DEFAULT 0
  COMMENT '代付自审开关（0=平台审核；1=商户门户自助审核下发/拒绝，平台不再管）'
  AFTER `auto_disbursement_threshold`;
